/**
 * Procura alimentos na base local com suporte a filtro por categoria e busca textual flexível
 */
export function searchOfflineFoods(query: string, categoryFilter?: FoodCategory | string): FoodDatabaseItem[] {
  let list = OFFLINE_FOOD_DATABASE;

  if (categoryFilter && categoryFilter !== 'todos') {
    list = list.filter((item) => item.category === categoryFilter);
  }

  const q = query.toLowerCase().trim();
  if (!q) return list;

  return list.filter((item) => {
    if (item.name.toLowerCase().includes(q)) return true;
    if (item.servingDescription.toLowerCase().includes(q)) return true;
    if (item.micros && item.micros.toLowerCase().includes(q)) return true;
    return item.aliases.some(
      (alias) => alias.toLowerCase().includes(q) || q.includes(alias.toLowerCase())
    );
  });
}

/**
 * Calcula calorias e macronutrientes de forma matemática pela regra dos 4-4-9:
 * Calorias = (Proteína * 4) + (Carboidratos * 4) + (Gordura * 9)
 */
export function calculatePortionNutrition(food: FoodDatabaseItem, amountGrams: number) {
  const multiplier = Math.max(0, amountGrams) / 100;
  const protein = Number((food.proteinPer100g * multiplier).toFixed(1));
  const carbs = Number((food.carbsPer100g * multiplier).toFixed(1));
  const fat = Number((food.fatPer100g * multiplier).toFixed(1));
  const fiber = Number((food.fiberPer100g * multiplier).toFixed(1));

  // Cálculo matemático determinístico das calorias exatas
  const calories = Math.round(protein * 4 + carbs * 4 + fat * 9);

  return {
    protein,
    carbs,
    fat,
    fiber,
    calories,
    portion: `${amountGrams}g`,
  };
}

/**
 * Cálculo rápido de calorias a partir dos macros digitados manualmente (regra 4-4-9)
 */
export function calculateCaloriesFromMacros(proteinG: number, carbsG: number, fatG: number): number {
  return Math.round((Number(proteinG) || 0) * 4 + (Number(carbsG) || 0) * 4 + (Number(fatG) || 0) * 9);
}
